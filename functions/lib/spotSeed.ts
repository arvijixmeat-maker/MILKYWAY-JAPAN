const norm = (s: string) => s.replace(/[（(][^）)]*[）)]/g, '').replace(/\p{Extended_Pictographic}|️/gu, '').replace(/[\s・、。【】「」!！]/g, '').toLowerCase();

/** 기본 관광지를 아직 넣지 않았으면 넣는다. 넣은 수를 돌려준다 (이미 넣었으면 0). */
export async function seedSpotsOnce(db: any): Promise<number> {
    const marker = `${SEED_PREFIX}${SEED_VERSION}-`;
    const done = await db.prepare('SELECT 1 AS x FROM tourist_spots WHERE id LIKE ? LIMIT 1').bind(`${marker}%`).first();
    if (done) return 0;
    const rows = ((await db.prepare('SELECT name_kr FROM tourist_spots').all()).results || []) as Array<{ name_kr: string }>;
    const known = rows.map(r => norm(String(r.name_kr || ''))).filter(Boolean);
    const stmts = [];
    for (const [slug, region, name, sub, desc] of SEEDS) {
        const n = norm(name);
        if (known.some(k => k === n || (Math.min(k.length, n.length) >= Math.max(k.length, n.length) * 0.6 && (k.includes(n) || n.includes(k))))) continue;
        stmts.push(db.prepare(
            "INSERT OR IGNORE INTO tourist_spots (id, name_kr, name_local, address, description, images, region, is_active) VALUES (?, ?, ?, '', ?, '[]', ?, 1)",
        ).bind(`${marker}${slug}`, name, sub, desc, region));
    }
    if (stmts.length) await db.batch(stmts);
    return stmts.length;
}

export const SEED_COUNT = SEEDS.length;
