/** 일정 항목 종류 추정 — 이동·식사·체크인은 볼거리/경로 사진 후보에서 빠진다 (편집기·AI 초안 공용) */
export type ActivityKind = 'pickup' | 'transport' | 'meal' | 'checkin' | 'free' | 'activity' | 'sightseeing';
export const inferActivityType = (t: string): ActivityKind => {
    if (/(공항|픽업|미팅|도착|入国|空港|到着|ミーティング|お迎え)/.test(t)) return 'pickup';
    if (/(이동|출발|移動|出発|専用車で)/.test(t)) return 'transport';
    if (/(식사|조식|중식|석식|점심|저녁|食事|朝食|昼食|夕食|ランチ|ディナー)/.test(t)) return 'meal';
    if (/(체크인|숙박|チェックイン)/.test(t)) return 'checkin';
    if (/(자유|휴식|쇼핑|장보기|自由|ショッピング)/.test(t)) return 'free';
    if (/(체험|승마|낙타|공연|트레킹|体験|乗馬|ラクダ|公演|トレッキング)/.test(t)) return 'activity';
    return 'sightseeing';
};

/**
 * 고객이 견적 요청에 적은 희망 일정 글(예: 「2027-08-01 ~ 2027-08-04」, 「2027/8/1〜2027/8/4」)에서 날짜 두 개를 읽는다.
 * 확정 날짜가 아직 없을 때 견적 편집기의 출발일·도착일과 AI 초안의 일수에 쓴다 (편집기·서버 공용).
 */
export const periodDates = (period: unknown): { start: string; end: string } => {
    const found = [...String(period || '').matchAll(/(\d{4})\s*[-/.年]\s*(\d{1,2})\s*[-/.月]\s*(\d{1,2})/g)]
        .map(m => `${m[1]}-${m[2].padStart(2, '0')}-${m[3].padStart(2, '0')}`)
        .filter(d => !Number.isNaN(Date.parse(d)));
    const start = found[0] || '';
    const end = found[1] && found[1] >= start ? found[1] : '';
    return { start, end };
};
