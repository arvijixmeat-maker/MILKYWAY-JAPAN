const norm = (s: string) => s.replace(/[\s·・,、（）()「」-]/g, '').toLowerCase();

const ENTRIES: Array<{ key: string; ll: [number, number] }> = RAW
    .flatMap(([lat, lon, names]) => names.map(n => ({ key: norm(n), ll: [lat, lon] as [number, number] })))
    // 긴 이름부터 비교해 「空港」보다 「チンギスハーン国際空港」이, 「ゴビ」보다 「ミニゴビ」가 먼저 잡히게 한다
    .sort((a, b) => b.key.length - a.key.length);

/** 이름(한/일/영)으로 좌표를 찾는다. 못 찾으면 null */
export function lookupPlace(name?: string | null): [number, number] | null {
    if (!name) return null;
    const k = norm(name);
    if (!k) return null;
    const exact = ENTRIES.find(e => e.key === k);
    if (exact) return exact.ll;
    const hit = ENTRIES.find(e => e.key.length >= 2 && k.includes(e.key));
    return hit ? hit.ll : null;
}

/** 여러 후보 문자열 중 처음으로 좌표가 잡히는 것을 쓴다 */
export function lookupFirst(...names: Array<string | null | undefined>): [number, number] | null {
    for (const n of names) {
        const ll = lookupPlace(n);
        if (ll) return ll;
    }
    return null;
}
